-- 1. Users Table
CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('admin', 'staff')),
  active INTEGER NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc', now())
);

-- 2. Rooms Table
CREATE TABLE IF NOT EXISTS rooms (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  number TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  type TEXT NOT NULL DEFAULT 'AC Room',
  rate NUMERIC NOT NULL DEFAULT 0,
  capacity INTEGER NOT NULL DEFAULT 2,
  amenities TEXT NOT NULL DEFAULT '',
  maintenance INTEGER NOT NULL DEFAULT 0
);

-- 3. Halls Table
CREATE TABLE IF NOT EXISTS halls (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  capacity INTEGER NOT NULL DEFAULT 100,
  rate_full NUMERIC NOT NULL DEFAULT 0,
  rate_half NUMERIC NOT NULL DEFAULT 0,
  description TEXT NOT NULL DEFAULT '',
  is_combo INTEGER NOT NULL DEFAULT 0,
  included_hall_ids TEXT NOT NULL DEFAULT ''
);

-- 4. Room Bookings Table
CREATE TABLE IF NOT EXISTS room_bookings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_id BIGINT NOT NULL REFERENCES rooms(id) ON DELETE CASCADE,
  guest_name TEXT NOT NULL,
  phone TEXT NOT NULL DEFAULT '',
  id_proof TEXT NOT NULL DEFAULT '',
  address TEXT NOT NULL DEFAULT '',
  guests INTEGER NOT NULL DEFAULT 1,
  check_in DATE NOT NULL,
  check_out DATE NOT NULL,
  rate NUMERIC NOT NULL DEFAULT 0,
  discount NUMERIC NOT NULL DEFAULT 0,
  total NUMERIC NOT NULL DEFAULT 0,
  paid NUMERIC NOT NULL DEFAULT 0,
  id_photo_taken INTEGER NOT NULL DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'reserved',
  notes TEXT NOT NULL DEFAULT '',
  created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc', now())
);

-- 5. Hall Bookings Table (with extra charges: power bill & generator)
CREATE TABLE IF NOT EXISTS hall_bookings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hall_id BIGINT NOT NULL REFERENCES halls(id) ON DELETE CASCADE,
  customer_name TEXT NOT NULL,
  phone TEXT NOT NULL DEFAULT '',
  event_type TEXT NOT NULL DEFAULT '',
  event_date DATE NOT NULL,
  slot TEXT NOT NULL DEFAULT 'full',
  guests INTEGER NOT NULL DEFAULT 0,
  rent NUMERIC NOT NULL DEFAULT 0,
  power_start NUMERIC NOT NULL DEFAULT 0,
  power_end NUMERIC NOT NULL DEFAULT 0,
  power_units NUMERIC NOT NULL DEFAULT 0,
  power_rate NUMERIC NOT NULL DEFAULT 15,
  power_amount NUMERIC NOT NULL DEFAULT 0,
  generator_type TEXT NOT NULL DEFAULT '',
  generator_hours NUMERIC NOT NULL DEFAULT 0,
  generator_rate NUMERIC NOT NULL DEFAULT 0,
  generator_amount NUMERIC NOT NULL DEFAULT 0,
  total NUMERIC NOT NULL DEFAULT 0,
  paid NUMERIC NOT NULL DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'confirmed',
  notes TEXT NOT NULL DEFAULT '',
  created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc', now())
);

-- 6. Payments Table
CREATE TABLE IF NOT EXISTS payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind TEXT NOT NULL CHECK (kind IN ('room', 'hall')),
  booking_id BIGINT NOT NULL,
  amount NUMERIC NOT NULL,
  method TEXT NOT NULL DEFAULT 'Cash',
  note TEXT NOT NULL DEFAULT '',
  paid_on DATE NOT NULL,
  created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc', now())
);

-- 7. Supplies Table
CREATE TABLE IF NOT EXISTS supplies (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  category TEXT NOT NULL DEFAULT 'General',
  unit TEXT NOT NULL DEFAULT 'pcs',
  quantity NUMERIC NOT NULL DEFAULT 0,
  min_quantity NUMERIC NOT NULL DEFAULT 0,
  unit_cost NUMERIC NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc', now())
);

-- 8. Stock Moves Table
CREATE TABLE IF NOT EXISTS stock_moves (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supply_id BIGINT NOT NULL REFERENCES supplies(id) ON DELETE CASCADE,
  type TEXT NOT NULL CHECK (type IN ('in', 'out', 'adjust')),
  quantity NUMERIC NOT NULL,
  balance NUMERIC NOT NULL,
  note TEXT NOT NULL DEFAULT '',
  created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc', now())
);

-- 9. Activity Log Table
CREATE TABLE IF NOT EXISTS activity (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  action TEXT NOT NULL,
  details TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc', now())
);

-- 10. Settings & Tariffs Table
CREATE TABLE IF NOT EXISTS settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

-- Indexes for fast queries
CREATE INDEX IF NOT EXISTS idx_room_bookings ON room_bookings(room_id, check_in);
CREATE INDEX IF NOT EXISTS idx_hall_bookings ON hall_bookings(hall_id, event_date);
CREATE INDEX IF NOT EXISTS idx_payments ON payments(kind, booking_id);
CREATE INDEX IF NOT EXISTS idx_stock_moves ON stock_moves(supply_id);

